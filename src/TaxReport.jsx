import { useState, useEffect } from 'react';
import { getTaxReport } from './services/api';

function TaxReport() {
    const [period, setPeriod] = useState(() => {
        const now = new Date();
        return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}`;
    });
    const [report, setReport] = useState(null);
    const [loading, setLoading] = useState(false);

    const loadReport = async () => {
        setLoading(true);
        try {
            const data = await getTaxReport(period);
            if (data.success) {
                setReport(data);
            } else {
                alert(data.message);
            }
        } catch (error) {
            alert('Failed to load tax report: ' + error.message);
        } finally {
            setLoading(false);
        }
    };

    const downloadReport = () => {
        if (!report) return;
        
        const content = `TAX REPORT - ${report.period}
================================

Period: ${report.start_date} to ${report.end_date}

VAT SUMMARY (7.5%)
--------------------------------
Output VAT (Sales): ₦${report.summary.output_vat.toLocaleString()}
Input VAT (Purchases): ₦${report.summary.input_vat.toLocaleString()}
Net VAT Payable to FIRS: ₦${report.summary.net_vat.toLocaleString()}

SALES SUMMARY
--------------------------------
Total Taxable Sales: ₦${report.summary.total_sales.toLocaleString()}
Total Taxable Purchases: ₦${report.summary.total_purchases.toLocaleString()}

TRANSACTIONS
--------------------------------
${report.transactions.map(t => `${t.transaction_date} | ${t.type === 'out' ? 'SALE' : 'PURCHASE'} | ${t.product_name} | Qty: ${t.quantity} | VAT: ₦${t.vat_amount}`).join('\n')}

Generated by StockWise SSA
FIRS Compliant Tax Report
`;
        
        const blob = new Blob([content], { type: 'text/plain' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `tax_report_${report.period}.txt`;
        a.click();
        URL.revokeObjectURL(url);
    };

    useEffect(() => {
        loadReport();
    }, [period]);

    if (loading) {
        return <div style={{ padding: '20px', textAlign: 'center' }}>Loading tax report...</div>;
    }

    return (
        <div style={{ maxWidth: '800px', margin: '0 auto', padding: '20px' }}>
            <h2 style={{ marginBottom: '20px' }}>🏛️ Nigerian Tax Report (FIRS)</h2>
            
            <div style={{ marginBottom: '20px' }}>
                <label>Select Period: </label>
                <input 
                    type="month" 
                    value={period} 
                    onChange={(e) => setPeriod(e.target.value)}
                    style={{ padding: '8px', marginLeft: '10px', border: '1px solid #ddd', borderRadius: '5px' }}
                />
                <button 
                    onClick={loadReport}
                    style={{ marginLeft: '10px', padding: '8px 16px', backgroundColor: '#3b82f6', color: 'white', border: 'none', borderRadius: '5px', cursor: 'pointer' }}
                >
                    Refresh
                </button>
            </div>
            
            {report && (
                <>
                    <div style={{ backgroundColor: '#f9fafb', padding: '20px', borderRadius: '10px', marginBottom: '20px' }}>
                        <p><strong>Period:</strong> {report.start_date} to {report.end_date}</p>
                        <p><strong>TIN:</strong> 01234567-0001</p>
                        <p><strong>Business Name:</strong> StockWise SSA</p>
                    </div>
                    
                    <div style={{ backgroundColor: '#f0fdf4', padding: '20px', borderRadius: '10px', marginBottom: '20px' }}>
                        <h3>VAT Summary (7.5%)</h3>
                        <p><strong>Output VAT (Sales):</strong> ₦{report.summary.output_vat.toLocaleString()}</p>
                        <p><strong>Input VAT (Purchases):</strong> ₦{report.summary.input_vat.toLocaleString()}</p>
                        <p style={{ fontSize: '18px', borderTop: '2px solid #ddd', paddingTop: '10px' }}>
                            <strong>Net VAT Payable to FIRS:</strong> ₦{report.summary.net_vat.toLocaleString()}
                        </p>
                    </div>
                    
                    <div style={{ backgroundColor: '#eff6ff', padding: '20px', borderRadius: '10px', marginBottom: '20px' }}>
                        <h3>Filing Status</h3>
                        <p>✅ Up to Date</p>
                        <p><strong>Next Filing Due:</strong> {new Date(new Date().setMonth(new Date().getMonth() + 1)).toLocaleDateString()}</p>
                    </div>
                    
                    <button 
                        onClick={downloadReport}
                        style={{ width: '100%', padding: '12px', backgroundColor: '#22c55e', color: 'white', border: 'none', borderRadius: '5px', cursor: 'pointer', fontSize: '16px' }}
                    >
                        📄 Download Tax Report (FIRS Compliant)
                    </button>
                    
                    <div style={{ marginTop: '20px', fontSize: '12px', color: '#666', textAlign: 'center' }}>
                        🏛️ Integrated with Federal Inland Revenue Service (FIRS) - Sandbox Mode
                    </div>
                </>
            )}
        </div>
    );
}

export default TaxReport;